import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('docs/v2-assets.json', root)));
const out = new URL('packages/react-native/src/assets/v2/', root);
mkdirSync(out, { recursive: true });
const lines = [];
const imports = [],
  web = [];
const iconImports = [],
  iconWeb = new Map(),
  iconNative = new Map();
for (const asset of manifest.assets) {
  const bytes = readFileSync(new URL(asset.path, root));
  if (createHash('sha256').update(bytes).digest('hex') !== asset.sha256)
    throw Error(`Modified source asset ${asset.path}`);
  const name = asset.path.split('/').at(-1).replace('.svg', '');
  const symbol =
    asset.catalog === 'icons'
      ? `icon${iconImports.length}`
      : `asset${imports.length}`;
  const geometry = asset.geometry
    ? `, geometry: ${JSON.stringify(asset.geometry)}`
    : '';
  if (asset.catalog === 'icons') {
    iconImports.push(`import ${symbol} from './assets/${name}.svg';`);
    if (!iconWeb.has(asset.iconName)) {
      iconWeb.set(asset.iconName, []);
      iconNative.set(asset.iconName, []);
    }
    iconWeb
      .get(asset.iconName)
      .push(`    ${asset.size}: { src: ${symbol}, size: ${asset.size} },`);
    iconNative
      .get(asset.iconName)
      .push(
        `    ${asset.size}: { source: require('./assets/v2/${name}.png'), size: ${asset.size} },`,
      );
  } else {
    imports.push(`import ${symbol} from './assets/${name}.svg';`);
    web.push(
      `  '${name}': { src: ${symbol}, width: ${asset.width}, height: ${asset.height}${geometry} },`,
    );
  }
  // Rasterize the original artwork for native Image; layout retains Figma point dimensions.
  await sharp(bytes, { density: 216 })
    .png()
    .toFile(new URL(name + '.png', out).pathname);
  if (asset.catalog !== 'icons')
    lines.push(
      `  '${name}': { source: require('./assets/v2/${name}.png'), width: ${asset.width}, height: ${asset.height}${geometry} },`,
    );
}
writeFileSync(
  new URL('packages/react-native/src/v2-glyphs.generated.ts', root),
  '// Generated by scripts/generate-v2-assets.mjs. Do not edit.\nexport const nativeGlyphs = {\n' +
    lines.join('\n') +
    '\n} as const;\nexport type NativeGlyphName = keyof typeof nativeGlyphs;\n',
);
for (const [path, values, prefix] of [
  [
    'packages/svelte/src/lib/v2/icons.generated.ts',
    iconWeb,
    iconImports.join('\n') + '\n',
  ],
  ['packages/react-native/src/v2-icons.generated.ts', iconNative, ''],
]) {
  writeFileSync(
    new URL(path, root),
    '// Generated by scripts/generate-v2-assets.mjs. Do not edit.\n' +
      prefix +
      'export const icons = {\n' +
      [...values]
        .map(([name, sizes]) => `  '${name}': {\n${sizes.join('\n')}\n  },`)
        .join('\n') +
      '\n} as const;\nexport type IconName = keyof typeof icons;\nexport const iconNames = Object.keys(icons) as IconName[];\n',
  );
}
writeFileSync(
  new URL('packages/svelte/src/lib/v2/glyphs.ts', root),
  '// Generated by scripts/generate-v2-assets.mjs. Do not edit.\n' +
    imports.join('\n') +
    '\nexport const glyphs = {\n' +
    web.join('\n') +
    '\n} as const;\nexport type GlyphName = keyof typeof glyphs;\n',
);
